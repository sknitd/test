import SwiftUI
import MFCore

/// Shows exactly what would be sent and where. Cancel is the default button.
struct AIConfirmSendView: View {
    let text: String
    let templateName: String
    let endpoint: String
    let onDecision: (Bool) -> Void

    var body: some View {
        VStack(alignment: .leading, spacing: 12) {
            Label("Nothing has been sent yet", systemImage: "hand.raised.fill")
                .font(.headline)
            VStack(alignment: .leading, spacing: 4) {
                AIPanelFactRow(key: "Destination", value: AIText.host(ofEndpoint: endpoint))
                AIPanelFactRow(key: "Full address", value: endpoint)
                AIPanelFactRow(key: "Prompt template", value: templateName)
                AIPanelFactRow(key: "Length", value: "\(text.count) characters")
            }
            Text("Exactly this text will leave your Mac:")
                .font(.callout)
                .foregroundStyle(.secondary)
            AIPanelTextBox(text: text)
            HStack {
                Text("Turn this confirmation off in AI Integrations if you trust the service.")
                    .font(.caption)
                    .foregroundStyle(.secondary)
                    .fixedSize(horizontal: false, vertical: true)
                Spacer(minLength: 12)
                Button("Send") { onDecision(true) }
                Button("Cancel") { onDecision(false) }
                    .keyboardShortcut(.defaultAction)
            }
        }
        .padding(16)
        .frame(minWidth: 380, minHeight: 280)
    }
}

/// Shows the model's answer; the user decides what happens with it.
struct AIResultView: View {
    let result: String
    let templateName: String
    let onChoice: (AIResultChoice) -> Void

    var body: some View {
        VStack(alignment: .leading, spacing: 12) {
            Label(templateName.isEmpty ? "AI Result" : templateName, systemImage: "sparkles")
                .font(.headline)
            AIPanelTextBox(text: result)
            HStack {
                Text("Generated by the AI service; check it before relying on it.")
                    .font(.caption)
                    .foregroundStyle(.secondary)
                Spacer(minLength: 12)
                Button("Dismiss") { onChoice(.dismiss) }
                    .keyboardShortcut(.cancelAction)
                Button("Paste into Frontmost App") { onChoice(.paste) }
                Button("Copy") { onChoice(.copy) }
                    .keyboardShortcut(.defaultAction)
            }
        }
        .padding(16)
        .frame(minWidth: 380, minHeight: 280)
    }
}

struct AIPanelFactRow: View {
    let key: String
    let value: String

    var body: some View {
        HStack(alignment: .firstTextBaseline, spacing: 8) {
            Text(key)
                .foregroundStyle(.secondary)
                .frame(width: 110, alignment: .leading)
            Text(value)
                .textSelection(.enabled)
                .lineLimit(2)
                .truncationMode(.middle)
        }
        .font(.callout)
    }
}

/// Scrollable, selectable block of text.
struct AIPanelTextBox: View {
    let text: String

    var body: some View {
        ScrollView(.vertical) {
            Text(text)
                .font(.system(.body, design: .monospaced))
                .textSelection(.enabled)
                .frame(maxWidth: .infinity, alignment: .leading)
                .padding(8)
        }
        .frame(maxWidth: .infinity, maxHeight: .infinity)
        .background(
            RoundedRectangle(cornerRadius: 6)
                .fill(Color(nsColor: .textBackgroundColor))
        )
        .overlay(
            RoundedRectangle(cornerRadius: 6)
                .stroke(Color.secondary.opacity(0.3), lineWidth: 1)
        )
    }
}
